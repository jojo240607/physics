//! phy-granular: 颗粒介质(离散元法 / 位置动力学)。
//!
//! 路线图 #7。采用 Position-Based Dynamics(PBD)框架模拟大量球面颗粒
//! (沙、谷物、颗粒堆积),特点:
//!
//! - **无条件稳定**:走"预测-约束投影-速度回写"路线,而非显式受力积分,
//!   对海量接触约束不会爆炸。
//! - **非穿透球-球接触**:用单边距离约束(间隙 < 0 时投影分离),按反质量
//!   加权把两球沿连线推开,实现堆积/堆叠。
//! - **边界约束**:盒形容器(地面 + 四面墙 + 顶),颗粒越界即夹回,模拟料斗/箱。
//! - **摩擦(近似)**:接触切向相对速度经切向阻尼衰减,维持堆积角。
//!
//! 与 `phy-soft` 的布料 PBD 不同,此处约束是**动态生成的**(每步据邻近
//! 关系重建球-球接触),而非固定拓扑网格。

